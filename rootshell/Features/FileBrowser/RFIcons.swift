    static func resolve(_ entry: RFEntry) -> RFIconDef {
        let name = entry.name
        if let match = files[name] ?? files[name.lowercased()] {
            return match
        }
        if entry.isDirectory {
            if let match = dirs[name] ?? dirs[name.lowercased()] {
                return match
            }
            return dirIcon
        }
        let ext = entry.fileExtension
        if !ext.isEmpty, let match = exts[ext] {
            return match
        }
        if entry.isSymlink { return linkIcon }
        if entry.isExecutable { return execIcon }
        return fileIcon
